using System;

namespace Task4
{
    class Program
    {
        static void Main(string[] args)
        {
            // Создаём массив из 15 элементов
            int[] numbers = new int[15];
            // Создаём объект Random для генерации случайных чисел
            Random rnd = new Random();
            // Переменная для суммы положительных чисел
            int sum = 0;
            // Переменная для количества положительных чисел
            int count = 0;
            // Заполняем массив случайными числами от -50 до 50
            for (int i = 0; i < numbers.Length; i++)
            {
                // Генерируем случайное число и записываем в массив
                numbers[i] = rnd.Next(-50, 51);
                // Выводим элемент массива на экран
                Console.Write(numbers[i] + " ");
            }
            // Переходим на новую строку после вывода массива
            Console.WriteLine();
            // Проходим по всем элементам массива
            for (int i = 0; i < numbers.Length; i++)
            {
                // Проверяем, является ли число положительным
                if (numbers[i] > 0)
                {
                    // Добавляем число к сумме
                    sum += numbers[i];
                    // Увеличиваем счётчик положительных чисел
                    count++;
                }
            }
            // Проверяем, есть ли вообще положительные числа
            if (count > 0)
            {
                // Вычисляем среднее значение положительных чисел
                double average = (double)sum / count;
                // Выводим результат на экран
                Console.WriteLine($"Среднее значение положительных чисел: {average}");
            }
            else
            {
                // Сообщаем, что положительных чисел нет
                Console.WriteLine("Положительных чисел в массиве нет.");
            }
        }
    }
}